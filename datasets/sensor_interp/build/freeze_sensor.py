from __future__ import annotations

import argparse
import json
import os
from collections import Counter
from typing import Any, Dict, List

import hashlib

import sensor_gen as G


def sha256_text(s: str) -> str:
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def write_jsonl(path: str, rows: List[Dict[str, Any]]) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False, sort_keys=True) + "\n")


def split_stats(items: List[Dict[str, Any]]) -> Dict[str, Any]:
    by_t = Counter(it["template"] for it in items)
    mc = sum(1 for it in items if it["template"] in ("T04", "T09", "T15"))
    return {
        "n": len(items),
        "by_level": {"L%d" % k: v for k, v in sorted(Counter(it["level"] for it in items).items())},
        "by_template": dict(sorted(by_t.items())),
        "by_setting": dict(sorted(Counter(it["meta"]["knobs"]["setting"] for it in items).items())),
        "answer_counts": {
            "T04": dict(Counter(it["answer"] for it in items if it["template"] == "T04")),
            "T08_none": sum(1 for it in items if it["template"] == "T08" and it["answer"] == "none"),
            "T09": dict(Counter(it["answer"] for it in items if it["template"] == "T09")),
            "T11_none": sum(1 for it in items if it["template"] == "T11" and it["answer"] == "none"),
            "T14_none": sum(1 for it in items if it["template"] == "T14" and it["answer"] == "none"),
            "T15": dict(sorted(Counter(it["answer"] for it in items if it["template"] == "T15").items())),
        },
        "closed_choice_share": round(mc / len(items), 4),
        "mean_attempts": round(sum(it["meta"]["attempts"] for it in items) / len(items), 3),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True, help="output folder")
    args = ap.parse_args()
    out_dir = args.out
    os.makedirs(out_dir, exist_ok=True)

    splits = {s: G.generate_split(s) for s in G.SPLITS}
    seeds, prompts = set(), set()
    for s, items in splits.items():
        bad = [it["id"] for it in items if not G.verify_item(it)[0]]
        assert not bad, ("verifier disagreement", s, bad[:5])
        for it in items:
            assert it["seed"] not in seeds, ("shared seed", it["id"])
            key = sha256_text(it["system"] + "\n" + it["question"])
            assert key not in prompts, ("shared prompt", it["id"])
            seeds.add(it["seed"])
            prompts.add(key)
        write_jsonl(os.path.join(out_dir, s + ".jsonl"), items)

    info = {
        "description": "Task family 2, sensor interpretation: synthetic, generated by sensor_gen.py (version %s), "
                       "gold by construction and re-derived by an independent verifier for every item. "
                       "test is the evaluation suite, heldout is reserved for confirmation runs (not used for prompt tuning), "
                       "calib is for the difficulty calibration only (disjoint seeds; knob settings rotate over mid, easy, hard). "
                       "test and heldout use the mid knob setting." % G.GEN_VERSION,
        "gen_version": G.GEN_VERSION,
        "seeds": {s: cfg["seed"] for s, cfg in G.SPLITS.items()},
        "counts": {s: len(v) for s, v in splits.items()},
        "per_level_target": {s: {"L%d" % k: v for k, v in cfg["per_level"].items()} for s, cfg in G.SPLITS.items()},
        "knobs": {str(lv): {k: dict(zip(("rows", "n_channels", "margin", "distractors", "closed_set"), v))
                            for k, v in d.items()} for lv, d in G.LEVEL_KNOBS.items()},
        "stats": {s: split_stats(v) for s, v in splits.items()},
    }
    with open(os.path.join(out_dir, "SPLIT.json"), "w", encoding="utf-8") as f:
        json.dump(info, f, indent=1)
        f.write("\n")

    print(json.dumps({"counts": info["counts"], "by_level": {s: info["stats"][s]["by_level"] for s in splits}}, indent=1))


if __name__ == "__main__":
    main()
