def finite(x: Any) -> bool:
    return isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(x)


def fnum(s: Any) -> Optional[float]:
    if s is None or s == "":
        return None
    try:
        v = float(s)
    except (TypeError, ValueError):
        return None
    return v if math.isfinite(v) else None


def read_csv(name: str, data_dir: Optional[str] = None) -> List[Dict[str, str]]:
    p = os.path.join(data_dir or DATA, name)
    if not os.path.exists(p) and os.path.exists(p + ".gz"):
        p += ".gz"
    if not os.path.exists(p):
        raise FileNotFoundError(p)
    opener = gzip.open if p.endswith(".gz") else open
    with opener(p, "rt", encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def have(name: str, data_dir: Optional[str] = None) -> bool:
    p = os.path.join(data_dir or DATA, name)
    return os.path.exists(p) or os.path.exists(p + ".gz")


def write_csv(path: str, rows: Sequence[Dict[str, Any]], columns: Sequence[str]) -> str:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(columns)
        for r in rows:
            w.writerow([fmt(r.get(c)) for c in columns])
    return path


def fmt(v: Any) -> str:
    if v is None:
        return ""
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, float):
        return "" if not math.isfinite(v) else repr(round(v, 10))
    return str(v)


def read_json(path: str, default: Any = None) -> Any:
    if not os.path.exists(path):
        return default
    with open(path, "r", encoding="utf-8") as fh:
        return json.load(fh)


def tex_escape(s: str) -> str:
    return s.replace("\\", "").replace("&", "\\&").replace("%", "\\%").replace("_", "\\_").replace("#", "\\#").replace("|", "/")


def f3(x: Any, nd: int = 3) -> str:
    return "---" if not finite(x) else f"{x:.{nd}f}"


def write_tex(path: str, body: str, source: str) -> str:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    head = f"% Generated by scripts from data/{source}. Do not edit by hand; regenerate with scripts/make_all.sh.\n"
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(head + body)
    return path


def mean(xs: Iterable[Optional[float]]) -> Optional[float]:
    v = [x for x in xs if x is not None]
    return sum(v) / len(v) if v else None
