from __future__ import annotations

import math
import os
from typing import Any, Dict, List, Sequence


def finite(x: Any) -> bool:
    return isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(x)


def tex_escape(s: str) -> str:
    return s.replace("\\", "").replace("&", "\\&").replace("%", "\\%").replace("_", "\\_").replace("#", "\\#").replace("|", "/")


def f3(x: Any, nd: int = 3) -> str:
    return "n/a" if not finite(x) else f"{x:.{nd}f}"


def write_tex(out_dir: str, name: str, body: str, source: str) -> str:
    os.makedirs(out_dir, exist_ok=True)
    head = f"% Generated by scripts from {source}. This file is not edited by hand.\n"
    path = os.path.join(out_dir, name)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(head + body)
    return path


def tab_level_a(rows: Sequence[Dict[str, Any]], out_dir: str) -> Dict[str, str]:
    co = any(r.get("colocation_gap") is not None for r in rows)
    if co:
        cap = ("Level A cross-family evidence at INT4 on the E-L class: tool-call accuracy (family 1 suite), weights, key-value cache, 95th-percentile latency at 4,096 prompt tokens with 16 concurrent "
               "requests in isolation and under co-location (all edge nodes loaded and the cloud active), and their ratio (co-location gap).")
        head = ("\\textbf{Family} & \\textbf{Size} & \\textbf{Acc.} & \\textbf{Weights (GiB)} & \\textbf{KV (tokens)} & \\textbf{p95 isolated (s)} & \\textbf{p95 co-located (s)} & "
                "\\textbf{Co-location gap} \\\\")
        cells = lambda r: f"{f3(r['p95_iso'], 1)} & {f3(r['p95_col'], 1)} & {f3(r['colocation_gap'], 2)}"
    else:
        cap = ("Level A cross-family evidence at INT4 on the E-L class: tool-call accuracy (family 1 suite), weights, key-value cache, 95th-percentile latency at 4,096 prompt tokens with one and with "
               "16 concurrent requests, and their ratio (concurrency gap).")
        head = ("\\textbf{Family} & \\textbf{Size} & \\textbf{Acc.} & \\textbf{Weights (GiB)} & \\textbf{KV (tokens)} & \\textbf{p95 c1 (s)} & \\textbf{p95 c16 (s)} & "
                "\\textbf{Concurrency gap} \\\\")
        cells = lambda r: f"{f3(r['p95_c1'], 2)} & {f3(r['p95_c16'], 1)} & {f3(r['gap'], 1)}"
    body = ["\\begin{table}[!t]", "\\centering", f"\\caption{{{cap}}}", "\\label{tab:levela}", "\\small", "\\begin{tabular}{@{}llcccccc@{}}", "\\toprule", head, "\\midrule"]
    for r in rows:
        body.append(f"{tex_escape(r['family'])} & {r['size']} & {f3(r['quality'])} & {f3(r['weights_gib'], 2)} & {r['kv_tokens'] if r['kv_tokens'] is not None else 'n/a'} & {cells(r)} \\\\")
    body += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return {"tex": write_tex(out_dir, "tab_level_a.tex", "\n".join(body), "data/level_a.csv"), "column": "co-location gap" if co else "concurrency gap"}


def fmt_num(x: Any) -> str:
    if not finite(x):
        return "n/a"
    a = abs(x)
    if a >= 100:
        return f"{x:.0f}"
    if a >= 10:
        return f"{x:.1f}"
    if a >= 1:
        return f"{x:.2f}"
    if a >= 0.1:
        return f"{x:.3f}"
    return f"{x:.4f}"


OVERHEAD_GROUPS = (("Configuration switch", ("switch_pause_s", "switch_drain_s", "switch_wake_s", "switch_probe_s", "switch_resume_s", "switch_restart_s")),
                   ("Gateways, per request", ("gw_compose_ms", "gw_verify_ms", "gw_route_ms", "cloud_gw_admit_ms", "cascade_attempt_done_ms", "cascade_attempt_escalated_ms")),
                   ("Controller", ("controller_decide_ms", "controller_poll_ms", "controller_late_ms", "activation_rtt_s")),
                   ("Certification", ("look_analysis_s", "solve_ms")))


def tab_overhead(rows_in: Sequence[Dict[str, Any]], complete_rounds: int, out_dir: str) -> Dict[str, str]:
    rows = {r["id"]: r for r in rows_in}
    rnd = complete_rounds
    cap = ("Overheads of the mechanism, measured in the campaign logs: the pause of a configuration switch by the sleep path with its components, the gateway time per request "
           "(composition and verification of the request, routing and admission on an idle node), the edge attempt of the token-budget escalation, the controller's cost per decision, "
           "poll and epoch boundary, the look analysis and one solve of the certified program. Times are medians and percentiles over the logged events"
           + (f" of {rnd} complete rounds" if rnd else "") + "; the routing time is an upper bound because the router decision is not logged on its own.")
    lines = ["\\begin{table}[!t]", "\\centering", f"\\caption{{{cap}}}", "\\label{tab:overhead}", "\\small", "\\begin{tabular}{@{}llrrrrr@{}}", "\\toprule",
             "\\textbf{Component} & \\textbf{Unit} & \\textbf{n} & \\textbf{Median} & \\textbf{p95} & \\textbf{p99} & \\textbf{Max} \\\\"]
    for g, ids in OVERHEAD_GROUPS:
        lines.append("\\midrule")
        lines.append(f"\\multicolumn{{7}}{{@{{}}l}}{{\\emph{{{g}:}}}} \\\\")
        for i in ids:
            r = rows.get(i)
            if not r:
                continue
            lab = tex_escape(r["label"].strip())
            if r["label"].startswith("  "):
                lab = "\\quad " + lab
            lines.append(f"{lab} & {r['unit']} & {r.get('n', 0)} & {fmt_num(r.get('median'))} & {fmt_num(r.get('p95'))} & {fmt_num(r.get('p99'))} & {fmt_num(r.get('max'))} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return {"tex": write_tex(out_dir, "tab_overhead.tex", "\n".join(lines), "data/overhead.csv (final campaign logs)")}
