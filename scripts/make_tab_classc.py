import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DATA = os.path.join(ROOT, "data")
TABS = os.path.join(ROOT, "out", "tables")
ARMS = (("I1-E", "Incumbent (I1-E)"), ("q35-4b-ih-w8a8|b8|c32|f1prio", "Cascade, priority"), ("q35-4b-ih-w8a8|b8|c32|fifo", "Cascade, FIFO"))
ROWS = (("Y_D_C", "All class C misses"), ("Y_D_C1", "Class C device control (5 s)"))


def main():
    sweep = list(csv.DictReader(open(os.path.join(DATA, "classc_sweep.csv"))))
    arms = {(r["row"], r["arm"]): r for r in csv.DictReader(open(os.path.join(DATA, "classc_rows.csv")))}
    out = ["% Generated by scripts/make_tab_classc.py from data/classc_sweep.csv and classc_rows.csv. Do not edit by hand.",
           "\\begin{table*}[!t]", "\\centering",
           "\\caption{Class C deadline sensitivity of the certificate. Certified from: the smallest budget of the added row at which a policy is certified; plug-in from: the same "
           "with point estimates. One row of class C deadline misses is added to the day-7 program and its budget is swept from 0.02 to "
           "0.25; every planned budget stays. Offline sensitivity on the campaign data with the estimator, radius and coupling rule of the campaign (level for 9 outcomes). Below the smallest certified budget no policy is certified and the incumbent is kept.}",
           "\\label{tab:classc}", "\\small",
           "\\begin{tabular}{@{}lccccc@{}}", "\\toprule",
           "\\multicolumn{6}{@{}l}{\\emph{A. Program with the added row}} \\\\",
           "\\textbf{Added row} & \\textbf{Certified from} & \\textbf{Plug-in from} & \\textbf{Certified weights} & \\textbf{Quality cost bound} & "
           "\\textbf{Cloud share} \\\\", "\\midrule"]
    for key, lab in ROWS:
        assert {r["binding"] for r in sweep if r["row"] == key and r["certified"] == "1"} == {"Y_C;Y_L_f1"}
        cert = [r for r in sweep if r["row"] == key and r["certified"] == "1"]
        plug = [r for r in sweep if r["row"] == key and r["plugin_found"] == "1"]
        c, p = cert[0], plug[0]
        w = " / ".join(f"{float(c['w_' + a]):.3f}" for a, _ in ARMS)
        out.append(f"{lab} & {float(c['budget']):.3f} & {float(p['budget']):.3f} & {w} & {float(c['quality_cost_bound']):.4f} & {float(c['cloud_share_center']):.3f} \\\\")
    out += ["\\midrule", "\\multicolumn{6}{@{}l}{\\emph{B. Miss shares per arm at day 7 (center; certified upper bound)}} \\\\",
            "\\textbf{Arm} & \\multicolumn{2}{c}{\\textbf{All class C misses}} & \\multicolumn{2}{c}{\\textbf{Device control (5 s)}} & \\\\",
            " & Center & Upper bound & Center & Upper bound & \\\\", "\\midrule"]
    for a, lab in ARMS:
        x, y = arms[("Y_D_C", a)], arms[("Y_D_C1", a)]
        out.append(f"{lab} & {float(x['center']):.3f} & {float(x['upper_cert']):.3f} & {float(y['center']):.3f} & {float(y['upper_cert']):.3f} & \\\\")
    out += ["\\bottomrule", "\\end{tabular}", "",
            "\\vspace{2pt}\\footnotesize Weights in the order incumbent / priority cascade / FIFO cascade; binding rows: cloud share and family 1 tail. Cloud share of the policy at "
            "the centers.", "\\end{table*}", ""]
    os.makedirs(TABS, exist_ok=True)
    p = os.path.join(TABS, "tab_classc.tex")
    open(p, "w").write("\n".join(out))
    print("wrote", p)


main()
