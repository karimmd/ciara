import os

import house as H

COST = (("Y_L_f1", "Tail 1"), ("Y_L_f2", "Tail 2"), ("Y_D", "Dead."), ("Y_E_A", "E-A"), ("Y_E_B", "E-B"), ("Y_E_C", "E-C"), ("Y_C", "Cloud"))
ARMS = (("CIARA", "CIARA"), ("I1-E", "Incumbent"), ("I1-S", "I1-S"), ("I1-oracle", "I1-Oracle"), ("I3", "Mix-or-Split"), ("I2", "RACE"), ("RecServe", "RecServe"),
        ("RecServe-ft", "RecServe-ft"), ("CB", "Bandit"), ("I1-E|c32", "Inc.\\ + cascade"), ("I1-E|f1prio", "Inc.\\ + priority"))


def shade(ratio):
    if ratio > 1.0:
        return "\\cellcolor{red!25}"
    if ratio >= 0.8:
        return "\\cellcolor{red!8}"
    return ""


def main():
    e = {(r["arm"], r["outcome"]): (H.fnum(r["mean"]), H.fnum(r["se"])) for r in H.read("e1e5_estimates.csv")}
    lines = ["% Generated by scripts/make_tab_methods_heat.py from data/e1e5_estimates.csv. Needs \\usepackage[table]{xcolor} and booktabs.",
             "\\begin{table*}[t]", "\\centering", "\\footnotesize", "\\setlength{\\tabcolsep}{4pt}",
             "\\caption{Comparison run: quality and the seven cost rows of every controller (arm means). A cell is shaded by its level at the mean plus two standard errors over its "
             "budget: light from 0.8 to 1, red above 1; the worst cell of each other controller is bold.}",
             "\\label{tab:methods-heat}",
             "\\begin{tabular}{l c " + "c " * len(COST) + "c}", "\\toprule",
             "Controller & Quality & " + " & ".join(lab for _, lab in COST) + " & Meets all \\\\",
             "Budget & & " + " & ".join(f"{H.BUDGETS[k]:.2f}" for k, _ in COST) + " & \\\\", "\\midrule"]
    for arm, name in ARMS:
        ratios = {k: (e[(arm, k)][0] + 2 * e[(arm, k)][1]) / H.BUDGETS[k] for k, _ in COST}
        worst = max(ratios, key=ratios.get)
        ok = all(v <= 1.0 for v in ratios.values())
        cells = []
        for k, _ in COST:
            txt = f"{e[(arm, k)][0]:.3f}"
            if arm != "CIARA" and k == worst and ratios[k] > 1.0:
                txt = f"\\textbf{{{txt}}}"
            cells.append(shade(ratios[k]) + txt)
        row = ("\\rowcolor{gray!12}" if arm == "CIARA" else "") + (f"\\textbf{{{name}}}" if arm == "CIARA" else name) + f" & {e[(arm, 'Y_Q')][0]:.3f} & " + \
            " & ".join(cells) + " & " + ("\\checkmark" if ok else "") + " \\\\"
        lines.append(row)
        print(f"{name:20s} worst {worst} {ratios[worst]:.3f} meets all {ok}")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    os.makedirs(H.TABS, exist_ok=True)
    p = os.path.join(H.TABS, "tab_methods_heat.tex")
    with open(p, "w") as fh:
        fh.write("\n".join(lines))
    print("wrote", p)


main()
